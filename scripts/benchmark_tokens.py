"""Measure actual payloads. A reduced-information AI prompt is a separate condition."""
import argparse
from importlib.metadata import version
import json
from pathlib import Path

import tiktoken

parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true", help="fail if committed measurements differ")
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
encodings = {name: tiktoken.get_encoding(name) for name in ["o200k_base", "cl100k_base"]}


def measure(label, text):
    return {"format": label, "utf8Bytes": len(text.encode("utf-8")),
            "characters": len(text), **{name: len(enc.encode(text)) for name, enc in encodings.items()}}


def read(path):
    return (root / path).read_text(encoding="utf-8")


full_json = json.loads(read("data/1tim.json"))
results = {
    "tokenizerPackage": f"tiktoken {version('tiktoken')}",
    "sourceSha256": full_json["metadata"]["sourceSha256"],
    "equalInformationPayloads": [
        measure("GNTC/1", read("data/1tim.gntc")),
        measure("JSON (indented)", read("data/1tim.json")),
        measure("JSON (minified)", json.dumps(full_json, ensure_ascii=False, separators=(",", ":"))),
        measure("TEI profile", read("data/1tim.tei.xml")),
    ],
    "separateReducedInformationCondition": measure("4:7-8 prompt, including legend and context closure; marker morphology only",
                                                  read("examples/1tim-4.7-8.prompt.txt")),
    "scope": "Counts of serialized payloads, not AI accuracy or a model-independent cost estimate. The full graph representations retain the same data; the separate prompt uses a selected passage and reduced morphology.",
}
json_text = json.dumps(results, ensure_ascii=False, indent=2) + "\n"
table = "| Format | UTF-8 bytes | o200k_base tokens | cl100k_base tokens |\n|---|---:|---:|---:|\n"
for row in results["equalInformationPayloads"]:
    table += f"| {row['format']} | {row['utf8Bytes']:,} | {row['o200k_base']:,} | {row['cl100k_base']:,} |\n"
prompt = results["separateReducedInformationCondition"]
markdown = f"""# Reproducible tokenizer measurements

Generated by `python scripts/benchmark_tokens.py` using `{results['tokenizerPackage']}`. Source SHA-256: `{results['sourceSha256']}`.

## Equal-information whole-book payloads

Each representation preserves the same complete 1 Timothy graph: source fields, candidate records, units, proposed connections, effects, alternatives, and metadata. JSON minification changes whitespace only. The measurements count actual committed/generated UTF-8 content, without a separate explanatory prompt. The TEI serialization contains conventional XML topology and explicit named feature structures, so its overhead reflects this project's profile rather than every possible TEI encoding.

{table}
These are tokenizer-specific input-size measurements, not claims of AI accuracy, latency, or universal compression ratios. A fair AI experiment must also count each format's instructions and definitions. Greek text and morphology remain in all four whole-book representations; the compact format is not stripping accents or replacing Greek with glosses.

## Separate task-specific prompt

The generated 4:7–8 prompt includes its legend, used vocabulary definitions, source metadata, referenced context, and morphology at retained connection markers. It contains **{prompt['o200k_base']:,} o200k_base tokens** and **{prompt['cl100k_base']:,} cl100k_base tokens** ({prompt['utf8Bytes']:,} UTF-8 bytes).

This prompt selects a passage and deliberately omits other morphology; its size is not a lossless whole-book compression result. Its context includes material outside the requested verses when a retained endpoint requires it.

## Reproduce

```sh
python -m pip install -r scripts/requirements.txt
dotnet run --project src/Gntc.Cli -- build .
python scripts/benchmark_tokens.py
python scripts/benchmark_tokens.py --check
```

The JSON results are in [`data/token-benchmarks.json`](../data/token-benchmarks.json). `--check` verifies both that file and this document. The initial conversation's single-record comparison (12 compact, 18 JSON-array, 69 TEI-feature tokens with o200k_base) was illustrative; these full artifacts are the repository benchmark.
"""
for relative, expected in [("data/token-benchmarks.json", json_text), ("docs/benchmarks.md", markdown)]:
    path = root / relative
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Stale benchmark: {relative}; regenerate with this tokenizer version.")
    else:
        path.write_text(expected, encoding="utf-8")
print(json.dumps(results, ensure_ascii=False, indent=2))
